"""Generate small vanilla replacement registries; reads masters without modifying them."""
import struct
from pathlib import Path
from inspect_master import subrecords,zlib

ROOT=Path(__file__).resolve().parents[1]
GAME=Path(r'M:\SteamLibrary\steamapps\common\Skyrim Special Edition\Data')
clothing={
    'ClothesBeggarRobes':0,'ClothesBeggarBoots':0,'ClothesBeggarHat':0,
    'ClothesFarmClothes01':1,'ClothesFarmBoots01':1,'ClothesFarmHat01':1,'ClothesFarmGloves03':1,
    'ClothesFineClothes01':2,'ClothesFineBoots01':2,'ClothesFineHat02':2,
    'ClothesMonkRobes':3,'ClothesMonkBoots':3,'ClothesMonkRobesHooded':3,
    'ClothesBlackSmith':4,'ClothesBlackSmithShoes':4,
    'ClothesBarKeeper':5,'ClothesBarKeeperShoes':5,
    'ClothesMerchantClothes':6,'ClothesMerchantBoots':6,'ClothesMerchantHat':6,
}
suffixes={'Sword':0,'Dagger':1,'WarAxe':2,'Mace':3,'Greatsword':4,'Battleaxe':5,'Warhammer':6,'Bow':7}
def main():
    rows=[]
    for master in ('Skyrim.esm','Dawnguard.esm'):
        with (GAME/master).open('rb') as f:
            while h:=f.read(24):
                tag,size,flags,form=struct.unpack_from('<4sIII',h)
                if tag==b'GRUP':continue
                if tag not in (b'ARMO',b'WEAP'):f.seek(size,1);continue
                raw=f.read(size)
                if flags&0x40000:raw=zlib.decompress(raw[4:])
                fields=dict(subrecords(raw));ed=fields.get(b'EDID',b'').rstrip(b'\0').decode()
                if b'ENAM' in fields or b'EITM' in fields:continue
                form&=0xFFFFFF
                if tag==b'ARMO' and ed in clothing:rows.append((master,form,0,clothing[ed],ed))
                if tag==b'ARMO' and any(ed=='Armor'+mat+slot for mat in ('Iron','Steel','Leather','Hide','Elven') for slot in ('Cuirass','CuirassA','CuirassB','Boots','BootsA','BootsB','Gauntlets','GauntletsA','GauntletsB','Helmet','HelmetA','HelmetB')):rows.append((master,form,1,0,ed))
                if tag==b'ARMO' and ed.startswith(('ArmorGuard','ArmorImperial','ArmorStormcloak')) and 'Shield' not in ed:rows.append((master,form,3,0,ed))
                if tag==b'WEAP':
                    for mat,group in [('Steel',0),('Elven',1),('Iron',2)]:
                        for suffix,kind in suffixes.items():
                            if ed==mat+suffix:rows.append((master,form,2,group,ed))
                    if ed in ('ImperialBow','HuntingBow','DLC1CrossBow'):rows.append((master,form,2,0,ed))
                    if ed=='LongBow':rows.append((master,form,2,2,ed))
    lines=['// Vanilla FormIDs only; generated by scripts/generate_restore_data.py.','#pragma once','namespace PL::Restore {','struct FormSpec { const char* plugin;unsigned form,kind,group;const char* editor; };','inline constexpr FormSpec forms[] = {']
    lines += [f'    {{"{m}",0x{f:06X},{k},{g},"{e}"}},' for m,f,k,g,e in rows]
    lines+=['};','}']
    (ROOT/'src/RestoreData.h').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print(f'Generated {len(rows)} replacement form bindings.')
if __name__=='__main__':main()
